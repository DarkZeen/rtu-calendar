def render_picker(data: Dict[str, Any], cfg) -> str:
    total = sum(s["count"] for s in data["subjects"])
    heading = cfg.calendar_name or "RTU nodarbibas"
    bits = []
    if cfg.semester_label:
        bits.append("<b>%s</b>" % _esc(cfg.semester_label))
    if cfg.group_label:
        bits.append(_esc(cfg.group_label))
    bits.append("semesterProgramId %d" % cfg.semester_program_id)

    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    payload = payload.replace("</", "<\\/")      # never close our own <script>

    out = _PAGE
    for token, value in (
        ("__TITLE__", _esc("%s — priekšmetu izvēle" % heading)),
        ("__EYEBROW__", "Nodarbību izvēle"),
        ("__HEADING__", _esc(heading)),
        ("__SUBTITLE__", " · ".join(bits)),
        ("__GENERATED__", data["generated"]),
        ("__EVENTS__", str(total)),
        ("__DATA__", payload),
    ):
        out = out.replace(token, value)
    return out


