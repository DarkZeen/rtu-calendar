"""Generates ``picker.html`` -- a standalone page for choosing subjects.

Everything is baked in at generation time: no fetches, no CDN, no fonts, no
build step. It therefore behaves identically opened from disk (``file://``) and
served from GitHub Pages, and the hourly workflow regenerates it so the subject
list can never drift from the live grid.

The page can commit your selection straight to GitHub, which is what makes the
calendar update without touching a terminal. That means holding a token, so:

* Content-Security-Policy pins the only reachable origin to ``api.github.com``
  and forbids every external script, style, font and image.
* The page is entirely self-contained -- nothing third-party can run in the
  origin that holds the token.
* The token is kept in memory only unless you explicitly ask otherwise, and the
  UI says plainly what it can do and how to revoke it.
* The edit is surgical: the ``include`` array is rewritten inside your original
  file text, so comments survive. The result is validated as JSON before it is
  ever sent, and a failed validation falls back to a clean re-serialisation.

Visual language follows mans.rtu.lv: pale mint ground, deep teal, mint pills,
16px radii, wide-tracked 12px labels.
"""

